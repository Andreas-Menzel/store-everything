#: Priority classes from 04-ingestion-pipeline.md Â§ prioritization: 0 = interactive,
#: 1 = presence, 2 = searchability, 3 = heavy derived, 4 = reprocessing. Lower runs first.
MIN_PRIORITY, MAX_PRIORITY = 0, 4


