#: "waiting for a retry" â a retryable failure returns to it with a later `next_due_at` â so
#: the only non-terminal states are `queued` and `running`.
OPERATION_STATES = (
    "queued",
    "running",
    "succeeded",
    "failed",
    "dead_letter",
    "cancelled",
    "superseded",
)

